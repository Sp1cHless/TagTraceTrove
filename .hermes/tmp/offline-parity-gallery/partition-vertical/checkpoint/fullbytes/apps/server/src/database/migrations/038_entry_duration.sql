-- A video's runtime on an Entry, the peer of page_count for a work that has no pages.
--
-- duration_seconds: whole seconds. It is stored as a number rather than as the `h:mm:ss` a page
-- shows for the same reason page_count is a number: the unit belongs to the column, and the one
-- place the display shape lives is `formatDuration`. An export may spell the field `duration` in
-- any of `h:mm:ss`, `mm:ss`, `m:ss`, `ss` or `s` (and a plain number is already seconds) — the
-- importer parses it, so what lands here is always seconds.
--
-- Nullable, and null is the ordinary case: most video pages compute the runtime inside their player
-- and publish nothing a rule can read, and a work with no runtime simply shows no duration.
ALTER TABLE entries ADD COLUMN duration_seconds INTEGER;
