from pathlib import Path
import argparse
import hashlib
import json
import os
import subprocess
import zipfile

parser = argparse.ArgumentParser()
parser.add_argument('--apk', required=True)
parser.add_argument('--version-code', required=True)
parser.add_argument('--version-name', required=True)
parser.add_argument('--previous', required=True)
parser.add_argument('--marker', action='append', default=[])
parser.add_argument('--report', required=True)
args = parser.parse_args()
root = Path(__file__).resolve().parents[2]
spike = root / 'spikes/001-android-webview-shell'
apk = Path(args.apk).resolve()
web = spike / 'web-dist'
checked = []
combined = b''
with zipfile.ZipFile(apk) as bundle:
    bundled = {name.removeprefix('assets/public/') for name in bundle.namelist() if name.startswith('assets/public/') and not name.endswith('/')}
    expected = {file.relative_to(web).as_posix() for file in web.rglob('*') if file.is_file()}
    native_only = {'cordova.js', 'cordova_plugins.js'}
    assert bundled - expected <= native_only and expected <= bundled, f'Bundled file set differs: extra={bundled-expected}, missing={expected-bundled}'
    for relative in sorted(bundled - expected):
        assert bundle.read('assets/public/' + relative) == (spike / 'android/app/src/main/assets/public' / relative).read_bytes(), f'Native-generated bytes differ: {relative}'
    for relative in sorted(expected):
        actual = bundle.read('assets/public/' + relative)
        assert actual == (web / relative).read_bytes(), f'Bundled bytes differ: {relative}'
        if relative.startswith('assets/'):
            assert actual == (root / 'apps/web/dist' / relative).read_bytes(), f'Web build bytes differ: {relative}'
        combined += actual
        checked.append(relative)
    for marker in args.marker:
        assert marker.encode() in combined, f'Missing bundle marker: {marker}'
env = dict(os.environ, JAVA_HOME=r'C:\Program Files\Eclipse Adoptium\jdk-21.0.7.6-hotspot')
build = spike / '.android-sdk/build-tools/36.0.0'
certs = []
for candidate in [apk, Path(args.previous).resolve()]:
    signed = subprocess.run([str(build / 'apksigner.bat'), 'verify', '--verbose', '--print-certs', str(candidate)], env=env, capture_output=True, text=True, check=True)
    certs.append(next(line for line in signed.stdout.splitlines() if 'certificate SHA-256 digest:' in line))
assert certs[0] == certs[1], 'Signer mismatch: upgrade would require reinstall'
badging = subprocess.run([str(build / 'aapt.exe'), 'dump', 'badging', str(apk)], capture_output=True, text=True, check=True)
package = next(line for line in badging.stdout.splitlines() if line.startswith('package:'))
assert f"versionCode='{args.version_code}'" in package and f"versionName='{args.version_name}'" in package, package
report = {'apk': str(apk), 'sha256': hashlib.sha256(apk.read_bytes()).hexdigest(), 'size': apk.stat().st_size, 'matchedWebFiles': checked, 'markers': args.marker, 'sameSignerAs': str(Path(args.previous).resolve()), 'certificate': certs[0], 'package': package}
Path(args.report).parent.mkdir(parents=True, exist_ok=True)
Path(args.report).write_text(json.dumps(report, indent=2), encoding='utf8')
print(json.dumps(report, indent=2))
