export const messages = {
  en,
  'zh-CN': zhCN,
} as const;

type MessageParameters = Record<string, string | number>;
type LocaleStorage = Pick<Storage, 'getItem' | 'setItem'>;

const localeStorageKey = 't3.locale';

function isLocale(value: string | null): value is Locale {
  return supportedLocales.some((locale) => locale === value);
}

function browserStorage(): LocaleStorage | undefined {
  return typeof window === 'undefined' ? undefined : window.localStorage;
}

function updateDocumentLanguage(locale: Locale): void {
  if (typeof document !== 'undefined') document.documentElement.lang = locale;
}

export interface I18nState {
  locale: Ref<Locale>;
  t: (key: MessageKey, parameters?: MessageParameters) => string;
  setLocale: (nextLocale: Locale) => void;
}

export function createI18nState(storage: LocaleStorage | undefined = browserStorage()): I18nState {
  const storedLocale = storage?.getItem(localeStorageKey) ?? null;
  const locale = ref<Locale>(isLocale(storedLocale) ? storedLocale : 'en');

  function t(key: MessageKey, parameters: MessageParameters = {}): string {
    return Object.entries(parameters).reduce(
      (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
      messages[locale.value][key],
    );
  }

  function setLocale(nextLocale: Locale): void {
    locale.value = nextLocale;
    storage?.setItem(localeStorageKey, nextLocale);
    updateDocumentLanguage(nextLocale);
  }

  updateDocumentLanguage(locale.value);
  return { locale, t, setLocale };
}

const appI18n = createI18nState();

export function useI18n(): I18nState {
  return appI18n;
}

export function setLocale(locale: Locale): void {
  appI18n.setLocale(locale);
}
